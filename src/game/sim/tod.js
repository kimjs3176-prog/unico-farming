/**
 * 시간대별 빛 색 (렌더링 무관, 테스트: tests/tod.test.js)
 * 하루를 몇 개의 기준 시각으로 나누고 그 사이를 부드럽게 이음 → 해 색이 한순간에 바뀌지 않음
 *  - sun: 햇빛(밤엔 달빛) 색, tint: 화면 전체 색 보정(곱), warmth: 밝은 곳 따뜻함, sat: 채도
 *  - 새벽 분홍빛 → 아침 금빛 → 한낮 맑은 흰빛 → 오후 노란빛 → 노을 주황 → 해질녘 보랏빛 → 밤 푸른빛
 */
const K = [
  // [시, 햇빛 색, 색 보정 rgb, 따뜻함, 채도]
  [0, 0x8ea6ff, [0.86, 0.92, 1.1], -0.02, 0.92],
  [4.5, 0x8ea6ff, [0.86, 0.92, 1.1], -0.02, 0.92],
  [5.6, 0xff9a78, [1.07, 0.95, 0.96], 0.07, 1.04],
  [7.3, 0xffd7a0, [1.05, 1.0, 0.95], 0.06, 1.12],
  [10, 0xfff3e0, [1.0, 1.0, 1.0], 0.035, 1.12],
  [15, 0xfff1dc, [1.0, 1.0, 0.99], 0.04, 1.12],
  [16.8, 0xffd9a8, [1.04, 0.99, 0.95], 0.06, 1.14],
  [18.0, 0xff8a52, [1.1, 0.94, 0.9], 0.1, 1.16],
  [19.2, 0xc58ad8, [0.98, 0.9, 1.04], 0.02, 1.02],
  [20.5, 0x8ea6ff, [0.86, 0.92, 1.1], -0.02, 0.92],
  [24, 0x8ea6ff, [0.86, 0.92, 1.1], -0.02, 0.92],
];
const rgb = (h) => [(h >> 16) & 255, (h >> 8) & 255, h & 255].map((v) => v / 255);
const lerp = (a, b, t) => a + (b - a) * t;
const smooth = (t) => t * t * (3 - 2 * t);

/** time: 하루 중 위치 0..1 → { sun:[r,g,b], tint:[r,g,b], warmth, sat } */
export function timeOfDay(time) {
  const h = (((time % 1) + 1) % 1) * 24;
  let i = 0;
  while (i < K.length - 2 && h >= K[i + 1][0]) i++;
  const a = K[i], b = K[i + 1], t = smooth((h - a[0]) / (b[0] - a[0] || 1));
  const sa = rgb(a[1]), sb = rgb(b[1]);
  return {
    sun: sa.map((v, k) => lerp(v, sb[k], t)),
    tint: a[2].map((v, k) => lerp(v, b[2][k], t)),
    warmth: lerp(a[3], b[3], t),
    sat: lerp(a[4], b[4], t),
  };
}
